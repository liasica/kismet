/**
 * 八字神煞查法表
 *
 * 每条神煞由「基准位 -> 命中值」的查表规则描述，调用方按 `base` 取出命中值列表，
 * 再在各柱的 `target` 部位比对即可，不需要为单条神煞写分支逻辑
 */

import type { PillarKind } from "../types"

/** 神煞查法的基准位 */
export type ShenShaBase =
  | "yearStem" // 以年干查
  | "yearBranch" // 以年支查
  | "monthBranch" // 以月支查
  | "dayStem" // 以日干查
  | "dayBranch" // 以日支查
  | "dayPillar" // 以日柱干支整体判定

/** 在目标柱的哪个部位匹配 */
export type ShenShaTarget = "stem" | "branch" | "sixtyCycle"

export interface ShenShaRule {
  name: string
  base: ShenShaBase
  target: ShenShaTarget
  /** 基准值 -> 命中值列表；`dayPillar` 基准用 "*" 作为唯一 key */
  table: Readonly<Record<string, readonly string[]>>
  /** 限定可以落在哪些柱，省略表示四柱都查 */
  scope?: readonly PillarKind[]
  /** 查法出处与流派说明 */
  note: string
}

