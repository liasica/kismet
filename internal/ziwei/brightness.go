// BrightnessOf 某星落在某宫的庙陷，杂曜或该星不可能落到的宫返回空串
func BrightnessOf(star string, branch int) string {
	row, ok := brightnessTable[star]
	if !ok {
		return ""
	}
	runes := []rune(row)
	if branch < 0 || branch >= len(runes) || runes[branch] == '-' {
		return ""
	}
	return string(runes[branch])
}
